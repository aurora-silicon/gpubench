    ("conv2d_v_gauss_cs", "conv2d_v_cs.hlsl", "cs", ["BILATERAL=0"]),
    ("conv2d_h_bilat_cs", "conv2d_h_cs.hlsl", "cs", ["BILATERAL=1"]),
    ("conv2d_v_bilat_cs", "conv2d_v_cs.hlsl", "cs", ["BILATERAL=1"]),
    ("fs_vs", "fs_vs.hlsl", "vs", []),
    ("color_ps", "color_ps.hlsl", "ps", []),
    ("texture_ps", "texture_ps.hlsl", "ps", []),
    ("geom_vs", "geom_vs.hlsl", "vs", []),
    ("draws_direct_vs", "draws_direct_vs.hlsl", "vs", []),
    ("draws_inst_vs", "draws_inst_vs.hlsl", "vs", []),
    ("draws_ps", "draws_ps.hlsl", "ps", []),
    ("deferred_geom_vs", "deferred_geom_vs.hlsl", "vs", []),
